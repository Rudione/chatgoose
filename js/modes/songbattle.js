    _whereAmI(name) {
      const uname = (name || '').toLowerCase();
      const now = Date.now();
      this._meCd = this._meCd || new Map();
      if (now - (this._meCd.get(uname) || 0) < 12000) return;
      this._meCd.set(uname, now);

      if (this.config.mode === 'teams') { this._teamsV2WhereAmI(name, uname); return; }

      const mine = this.state.tracks.filter(tk => (tk.submitter || '').toLowerCase() === uname);
      if (!mine.length) { this.toast('info', esc(name), tr('sbMeNone', 'У тебя пока нет треков — кидай через') + ' !' + this.config.command); return; }
      if (this.state.phase === 'lobby') {
        this.toast('info', esc(name), tr('sbMeLobby', 'Твои треки в лобби') + ': ' + mine.length + ' · ' + tr('sbMeLobbyWait', 'ждём старта'));
        return;
      }
      const dists = [];
      if (this.config.mode === 'king') {
        const k = this.state.king;
        const b = this.state.kingBattle;
        mine.forEach(tk => {
          if (k && k.id === tk.id) dists.push(-2);
          else if (b && (b.a === tk.id || b.b === tk.id)) dists.push(-1);
          else { const qi = (this.state.queue || []).indexOf(tk.id); if (qi > 0) dists.push(qi - 1); else if (qi === 0) dists.push(-1); }
        });
      } else if (this.config.mode === 'chart') {
        const c = this.state.chart;
        if (c) mine.forEach(tk => {
          const idx = c.order.indexOf(tk.id);
          if (idx === c.i) dists.push(-1);
          else if (idx > c.i) dists.push(idx - c.i - 1);
        });
      } else {
        const b = this._curBattle();
        let ahead = 0;
        outer:
        for (let ri = this.state.ri; ri < this.state.rounds.length; ri++) {
          const bs = this.state.rounds[ri].battles;
          for (let bi = (ri === this.state.ri ? this.state.bi : 0); bi < bs.length; bi++) {
            const bt = bs[bi];
            const isCur = ri === this.state.ri && bi === this.state.bi;
            const isMine = mine.some(tk => bt.a === tk.id || bt.b === tk.id);
            if (isMine) { dists.push(isCur ? -1 : ahead); break outer; }
            if (!isCur && bt.a && bt.b) ahead++;
          }
        }
      }
      if (!dists.length) { this.toast('info', esc(name), tr('sbMePlayed', 'Твои треки уже сыграли — жди следующей игры')); return; }
      const d = Math.min.apply(null, dists);
      if (d === -2) this.toast('ok', esc(name), '👑 ' + tr('sbMeThrone', 'Твой трек сейчас на троне!'));
      else if (d === -1) this.toast('ok', esc(name), '🎵 ' + tr('sbMeNow', 'Твой трек играет прямо сейчас!'));
      else if (d === 0) this.toast('info', esc(name), '⏭ ' + tr('sbMeNext', 'Твой трек следующий!'));
      else this.toast('info', esc(name), tr('sbMeAfter', 'Твой трек через') + ' ' + d + ' ' + tr('sbMeTracksWord', 'трек(а/ов)'));
    },

