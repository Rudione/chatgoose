    _teamsV2StartTournament() {
      this._teamsV2MigrateOrphans();
      const n = this.config.teamsV2.teamCount;
      const teams = this._teamsV2ReadyTeams();
      if (teams.length < n) {
        this.toast('warn', tr('sbTeamsNeedTitle', 'Нужны все команды'), tr('sbTeamsNeedAllMsg', 'В каждой команде должен быть хотя бы один игрок') + ` (${teams.length}/${n})`);
        return;
      }
      const order = teams.slice();
      for (let i = order.length - 1; i > 0; i--) { const j = (Math.random() * (i + 1)) | 0; const tmp = order[i]; order[i] = order[j]; order[j] = tmp; }
      const rounds = [];
      const r0 = [];
      for (let i = 0; i < order.length; i += 2) r0.push({ a: order[i], b: order[i + 1], winner: null, scoreA: 0, scoreB: 0 });
      rounds.push(r0);
      let slots = order.length / 2;
      while (slots > 1) {
        slots = slots / 2;
        rounds.push(Array.from({ length: slots }, () => ({ a: null, b: null, winner: null, scoreA: 0, scoreB: 0 })));
      }
      this.state.teamsV2.bracket = rounds;
      this.state.teamsV2.roundIdx = 0;
      this.state.teamsV2.matchIdx = 0;
      this.state.teamsV2.champion = null;
      this.state.rounds = []; this.state.king = null; this.state.chart = null;
      this.state.phase = 'battle';
      Sound.go && Sound.go();
      this._save();
      this._showPhase();
      this._teamsV2StartMatch();
    },

